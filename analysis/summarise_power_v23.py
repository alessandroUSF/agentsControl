"""Markdown summary of the v2.3 power simulations (analysis/output/power_sim_v23_*.json).

Usage: python -I analysis/summarise_power_v23.py [file.json ...]    (default: every power_sim_v23_*.json)
Writes analysis/output/power_sim_v23_summary.md and prints it. Reads simulation output only.
"""
import json
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent / "output"


def pct(x):
    return f"{100 * x:.1f}"


def pp(x):
    return f"{100 * x:+.2f}"


def table(rows):
    head = ("| shock SD | q0 | invalid | mode | target on / int | true on / int (pp) | SE on / int (pp) | "
            "Holm power on / int (%) | cover on / int (%) | bound -3/-5/-7 (%) | excl. on -2/-3/-5 (%) | "
            "excl. int -2/-3/-5 (%) | complete-case on (pp) | bounds on (pp) |")
    out = [head, "|" + "---|" * head.count("|")][:1] + ["|" + "---|" * (head.count("|") - 1)]
    for r in rows:
        s = r["scenario"]
        b, eo, ei = r["bound_reject"], r["exclude_on"], r["exclude_int"]
        out.append(
            f"| {s['sd_common']}/{s['sd_own']} | {s['q0']} | {s['inv']} | {s['mode']} | {s['theta_on']} / {s['iota']} | "
            f"{pp(r['true_on'])} / {pp(r['true_int'])} | {100 * r['se_on']:.2f} / {100 * r['se_int']:.2f} | "
            f"{pct(r['holm_reject_on'])} / {pct(r['holm_reject_int'])} | {pct(r['cover_on'])} / {pct(r['cover_int'])} | "
            f"{pct(b['0.03'])}/{pct(b['0.05'])}/{pct(b['0.07'])} | {pct(eo['0.02'])}/{pct(eo['0.03'])}/{pct(eo['0.05'])} | "
            f"{pct(ei['0.02'])}/{pct(ei['0.03'])}/{pct(ei['0.05'])} | {pp(r['complete_case_on'])} | "
            f"{pp(r['bounds_on'][0])} to {pp(r['bounds_on'][1])} |")
    return out


def groups(rows):
    head = ("| target on / int | mode | API on (pp), SE | local on (pp), SE | API int (pp), SE | local int (pp), SE | "
            "commercial / instruct-local / refusal-removed on (pp) |")
    out = [head, "|" + "---|" * (head.count("|") - 1)]
    for r in rows:
        s, a, l, g = r["scenario"], r["api"], r["local"], r["group_on"]
        out.append(
            f"| {s['theta_on']} / {s['iota']} | {s['mode']} | {pp(a['on'])}, {100 * a['se_on']:.2f} | "
            f"{pp(l['on'])}, {100 * l['se_on']:.2f} | {pp(a['int'])}, {100 * a['se_int']:.2f} | "
            f"{pp(l['int'])}, {100 * l['se_int']:.2f} | {pp(g['commercial'])} / {pp(g['instruct_local'])} / "
            f"{pp(g['refusal_removed'])} |")
    return out


def labelled(rows):
    head = ("| target on / int | mode | subset | positives | sens. change on (pp), SE | sens. author-minus-control (pp), SE | "
            "FP change on (pp), SE | FP author-minus-control (pp), SE |")
    out = [head, "|" + "---|" * (head.count("|") - 1)]
    for r in rows:
        s = r["scenario"]
        for tag, g in r.get("labelled", {}).items():
            out.append(
                f"| {s['theta_on']} / {s['iota']} | {s['mode']} | {tag} | {g['n_pos']:.0f} | "
                f"{pp(g['sens_on'])}, {100 * g['se_sens_on']:.2f} | {pp(g['sens_int'])}, {100 * g['se_sens_int']:.2f} | "
                f"{pp(g['fp_on'])}, {100 * g['se_fp_on']:.2f} | {pp(g['fp_int'])}, {100 * g['se_fp_int']:.2f} |")
    return out


def alts(rows):
    head = ("| q0 | invalid | target on / int | statistic | share | ratio on / int / blind (pp) | "
            "SE of ratio on / int / blind (pp) | Holm power on / int (%) | blind bound -3/-5/-7/-10 (%) |")
    out = [head, "|" + "---|" * (head.count("|") - 1)]
    for r in rows:
        s = r["scenario"]
        for tag, a in r["alt"].items():
            b = a["bound_reject"]
            out.append(
                f"| {s['q0']} | {s['inv']} | {s['theta_on']} / {s['iota']} | {tag} | {a['den']:.3f} | "
                f"{pp(a['ratio_on'])} / {pp(a['ratio_int'])} / {pp(a['ratio_blind'])} | "
                f"{100 * a['se_ratio_on']:.2f} / {100 * a['se_ratio_int']:.2f} / {100 * a['se_ratio_blind']:.2f} | "
                f"{pct(a['holm_reject_on'])} / {pct(a['holm_reject_int'])} | "
                f"{pct(b['0.03'])}/{pct(b['0.05'])}/{pct(b['0.07'])}/{pct(b['0.1'])} |")
    return out


def main():
    files = [Path(x) for x in sys.argv[1:]] or sorted(OUT.glob("power_sim_v23_*.json"))
    lines = ["# Power, size and coverage of the v2.3 yoked design (simulation summary)", "",
             "Generated by `analysis/summarise_power_v23.py` from the JSON files named below. All quantities are",
             "simulated; no study output was used. \"pp\" = percentage points.", ""]
    for f in files:
        d = json.loads(f.read_text(encoding="utf-8"))
        rows = d["rows"]
        if not rows:
            continue
        s0 = rows[0]["scenario"]
        extra = [f"{k} {s0[k]}" for k in ("sus", "se_removed", "screen_se", "screen_sp")
                 if s0.get(k, 0.0) not in (0.0, 1.0)] + (["structural null"] if s0.get("structural") else [])
        lines += [f"## {f.name}", "",
                  f"Side `{s0['side']}`; panel `{s0.get('panel', 'all')}`; yoking `{s0.get('yoke', 'access')}`; "
                  f"prompts per API judge {s0['n_api']}, per local judge {s0['n_local']}; "
                  f"{rows[0]['reps']} replications in {rows[0]['panels']} panels; {rows[0]['flips']} sign vectors; "
                  f"true blind self association set to {s0['beta_blind']}; Holm family alpha {s0['alpha_primary']}, "
                  f"blind bound alpha {s0['alpha_bound']}" + ("; " + ", ".join(extra) if extra else "") + ".", ""]
        lines += table(rows) + [""]
        if "alt" in rows[0]:
            lines += ["Alternative statistics on the same simulated data (`h11` = the eleven non-commercial judges; "
                      "`scr` = all 22 judges, answers that the refusal screen marks as non-refusals; `h11scr` = both). "
                      "\"Share\" = weight of the retained cells; \"ratio\" = effect among the retained answers:", ""]
            lines += alts(rows) + [""]
        few = [r for r in rows if r["scenario"]["q0"] == 0.10 and r["scenario"]["inv"] in ("3", "harm")
               and r["scenario"]["sd_common"] in (0.0, 0.3)][:40]
        lines += ["Group means (first 40 scenarios with q0 = 0.10):", ""] + groups(few) + [""]
        if "labelled" in rows[0]:
            lines += ["Label-conditioned changes (same scenarios; the simulated failure indicator stands in for the "
                      "human label; `all` = every answer of the frame, `bal` = 300 labelled answers with equal "
                      "quotas per author, `tilt` = 300 labelled answers tilted towards authors that produce "
                      "failures):", ""] + labelled(few[:12]) + [""]
    text = "\n".join(lines) + "\n"
    (OUT / "power_sim_v23_summary.md").write_text(text, encoding="utf-8")
    print(text)


if __name__ == "__main__":
    main()
